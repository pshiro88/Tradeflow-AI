const MONEY_PATTERN = /^\d{1,16}(\.\d{1,2})?$/

interface ReviewSheetProps {
  resultId: string | null
  onClose: () => void
}

export function ReviewSheet({ resultId, onClose }: ReviewSheetProps) {
  const { data, isPending, isError, error, refetch } = useReconciliationDetail(resultId)

  return (
    <Sheet open={!!resultId} onOpenChange={(open) => !open && onClose()}>
      <SheetContent className="w-full data-[side=right]:sm:max-w-2xl">
        <SheetHeader className="border-b">
          <SheetTitle>{data ? data.transaction_reference : 'Reconciliation result'}</SheetTitle>
          <SheetDescription>How this payment was matched, and what a person can do about it.</SheetDescription>
        </SheetHeader>
        <div className="flex-1 overflow-y-auto p-4">
          {isError ? (
            <ErrorState error={error} onRetry={() => void refetch()} title="Could not load this result" />
          ) : isPending ? (
            <div role="status" aria-label="Loading result" className="space-y-3">
              <Skeleton className="h-8 w-48" />
              <Skeleton className="h-24" />
              <Skeleton className="h-40" />
            </div>
          ) : (
            <ReviewBody key={data.id} detail={data} />
          )}
        </div>
      </SheetContent>
    </Sheet>
  )
}

function ReviewBody({ detail }: { detail: ReconciliationDetail }) {
  const invoiceCurrency = detail.invoice_currency ?? detail.currency
  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-center gap-3">
        <PaymentStatusBadge status={detail.status} />
        <span className="text-sm text-muted-foreground">
          {methodLabel(detail.match_method)} · confidence {confidenceLabel(detail.confidence)}
        </span>
      </div>

      <div className="rounded-lg border bg-muted/40 p-4">
        <p className="mb-1 text-xs font-medium tracking-wide text-muted-foreground uppercase">Explanation</p>
        <p className="text-sm whitespace-pre-line">{detail.explanation}</p>
        <p className="mt-2 text-xs text-muted-foreground">
          Generated by the deterministic reconciliation rules. Confidence is an estimate, not a probability.
        </p>
      </div>

      <ExplainWithAi resultId={detail.id} />

      <div className="grid gap-5 sm:grid-cols-2">
        <Section title="Payment">
          <Row label="Sender">{detail.sender_name}</Row>
          <Row label="Payment reference">{detail.payment_reference ?? '—'}</Row>
          <Row label="Transaction date">{formatDate(detail.transaction_date)}</Row>
          <Row label="Payment amount">{formatMoney(detail.payment_amount, detail.currency)}</Row>
          <Row label="Allocated">{formatMoney(detail.allocated_amount, detail.currency)}</Row>
          <Row label="Unallocated">{formatMoney(detail.payment_unallocated, detail.currency)}</Row>
        </Section>
        <Section title="Invoice">
          <Row label="Invoice">
            {detail.invoice_number && detail.invoice_id ? (
              <Link to={`/invoices/${detail.invoice_id}`} className="text-primary hover:underline">
                {detail.invoice_number}
              </Link>
            ) : (
              '—'
            )}
          </Row>
          <Row label="Invoice amount">
            {detail.invoice_amount ? formatMoney(detail.invoice_amount, invoiceCurrency) : '—'}
          </Row>
          <Row label="Previously received">
            {detail.previously_received ? formatMoney(detail.previously_received, invoiceCurrency) : '—'}
          </Row>
          <Row label="Outstanding after">
            {detail.outstanding_after ? formatMoney(detail.outstanding_after, invoiceCurrency) : '—'}
          </Row>
        </Section>
      </div>

      {detail.candidates.length > 0 && (
        <Section title="Potential invoice candidates">
          <ul className="space-y-2">
            {detail.candidates.map((c) => (
              <li key={c.invoice_id} className="rounded-lg border bg-card p-3 text-sm">
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <span className="font-medium">
                    {c.invoice_number} <span className="font-normal text-muted-foreground">· {c.buyer_name}</span>
                  </span>
                  <span className="tabular-nums">
                    {formatMoney(c.outstanding, c.currency)} <span className="text-muted-foreground">outstanding</span>
                  </span>
                </div>
                <p className="mt-1 text-muted-foreground">
                  {c.reason} (name match {c.name_score}%)
                </p>
              </li>
            ))}
          </ul>
        </Section>
      )}

      {/* A decision banner is always shown once someone has decided; actions remain if more can be done. */}
      {detail.review_decision !== 'NONE' && <ReviewOutcome detail={detail} />}
      {detail.needs_review && <ReviewActions detail={detail} />}
    </div>
  )
}

/** Plain-language explanation. The AI only rewords the engine's result; it cannot allocate or change anything. */
function ExplainWithAi({ resultId }: { resultId: string }) {
  const explain = useExplainDiscrepancy()
  const [result, setResult] = useState<DiscrepancyExplanation | null>(null)
  const [error, setError] = useState<string | null>(null)

  const run = () => {
    setError(null)
    explain.mutate(resultId, { onSuccess: setResult, onError: (e) => setError(getErrorMessage(e)) })
  }

  return (
    <section className="space-y-3" aria-label="Plain-language explanation">
      <Button type="button" variant="outline" size="sm" onClick={run} disabled={explain.isPending}>
        {explain.isPending ? <Loader2 className="size-4 animate-spin" /> : <Sparkles className="size-4" />}
        {result ? 'Explain again' : 'Explain in plain words'}
      </Button>
      {error && (
        <p role="alert" className="rounded-md bg-destructive/10 px-3 py-2 text-sm text-destructive">
          {error}
        </p>
      )}
      {result && (
        <div className="space-y-2 rounded-lg border bg-card p-3 text-sm">
          <AiLabel generatedBy={result.generated_by} />
          <p className="whitespace-pre-line">{result.explanation}</p>
          {result.ai_note && <p className="text-xs text-muted-foreground">{result.ai_note}</p>}
          <p className="text-xs text-muted-foreground">Explanations never change any data. Allocations are always a person's decision.</p>
        </div>
      )}
    </section>
  )
}

function ReviewOutcome({ detail }: { detail: ReconciliationDetail }) {
  const approved = detail.review_decision === 'APPROVED'
  return (
    <div
      className={cn(
        'flex items-start gap-3 rounded-lg border p-4 text-sm',
        approved ? 'border-success/30 bg-success/5' : 'bg-muted/40',
      )}
    >
      {approved ? (
        <CheckCircle2 className="mt-0.5 size-5 shrink-0 text-success" />
      ) : (
        <ThumbsDown className="mt-0.5 size-5 shrink-0 text-muted-foreground" />
      )}
      <div className="space-y-1">
        <p className="font-medium text-navy">
          {approved ? 'Allocation approved' : 'Candidate rejected'} by {detail.reviewed_by_name ?? 'a reviewer'}
          {detail.reviewed_at && <span className="font-normal text-muted-foreground"> · {formatDateTime(detail.reviewed_at)}</span>}
        </p>
        {detail.review_note && <p className="text-muted-foreground">“{detail.review_note}”</p>}
        <p className="text-xs text-muted-foreground">
          Recorded in the audit log.{!approved && ' The payment can still be allocated to a different invoice below.'}
        </p>
      </div>
    </div>
  )
}

function ReviewActions({ detail }: { detail: ReconciliationDetail }) {
  const eligible = useEligibleInvoices(detail.id, true)
  const approve = useApproveResult(detail.id)
  const reject = useRejectResult(detail.id)

  const [invoiceId, setInvoiceId] = useState(detail.invoice_id ?? detail.candidates[0]?.invoice_id ?? '')
  const [amount, setAmount] = useState('')
  const [note, setNote] = useState('')
  const [error, setError] = useState<string | null>(null)
  const [rejectOpen, setRejectOpen] = useState(false)

  const selected = eligible.data?.find((e) => e.invoice_id === invoiceId)
  const canReject = detail.status === 'MANUAL_REVIEW' || detail.status === 'MISMATCH'
  const busy = approve.isPending || reject.isPending

  const submitApprove = () => {
    setError(null)
    if (!invoiceId) return setError('Choose the invoice to allocate this payment to.')
    if (amount.trim() && !MONEY_PATTERN.test(amount.trim())) return setError('Enter a valid amount with up to 2 decimals.')
    approve.mutate(
      { invoice_id: invoiceId, amount: amount.trim() || undefined, note: note.trim() || undefined },
      {
        onSuccess: (result) => toast.success(`Allocated ${formatMoney(result.allocated_amount, result.currency)} to ${result.invoice_number}`),
        onError: (e) => setError(getErrorMessage(e)),
      },
    )
  }

  const submitReject = () =>
    reject.mutate(note.trim() || undefined, {
      onSuccess: () => {
        toast.success('Candidate rejected')
        setRejectOpen(false)
      },
      onError: (e) => {
        setRejectOpen(false)
        setError(getErrorMessage(e))
      },
    })

  return (
    <section className="space-y-4 rounded-lg border-2 border-primary/20 bg-primary/5 p-4" aria-label="Manual review">
      <div className="flex items-center gap-2">
        <UserCheck className="size-5 text-primary" />
        <h3 className="font-medium text-navy">Manual review</h3>
      </div>
      <p className="flex items-start gap-2 text-sm text-muted-foreground">
        <Lightbulb className="mt-0.5 size-4 shrink-0" />
        Only a person can move money here. The system will not allocate more than the invoice's outstanding balance or
        the payment's unallocated amount, and never across currencies.
      </p>

      <div className="space-y-2">
        <Label htmlFor="review-invoice">Allocate to invoice</Label>
        <NativeSelect id="review-invoice" value={invoiceId} onChange={(e) => setInvoiceId(e.target.value)} disabled={busy}>
          <option value="">{eligible.isPending ? 'Loading invoices…' : 'Select an invoice'}</option>
          {eligible.data?.map((e) => (
            <option key={e.invoice_id} value={e.invoice_id}>
              {e.invoice_number} · {e.buyer_name} · {formatMoney(e.outstanding, e.currency)} outstanding
              {e.is_candidate ? ' · suggested' : ''}
            </option>
          ))}
        </NativeSelect>
        {eligible.data?.length === 0 && (
          <p className="text-sm text-muted-foreground">
            No open {detail.currency} invoices can take this payment.
          </p>
        )}
        {selected && (
          <p className="text-xs text-muted-foreground">
            Invoice outstanding {formatMoney(selected.outstanding, selected.currency)} · payment unallocated{' '}
            {formatMoney(detail.payment_unallocated, detail.currency)}
          </p>
        )}
      </div>

      <div className="space-y-2">
        <Label htmlFor="review-amount">Amount to allocate (optional)</Label>
        <Input
          id="review-amount"
          inputMode="decimal"
          placeholder="Leave empty for the largest amount that fits"
          value={amount}
          onChange={(e) => setAmount(e.target.value)}
          disabled={busy}
        />
      </div>

      <div className="space-y-2">
        <Label htmlFor="review-note">Note (saved with the decision)</Label>
        <Textarea id="review-note" rows={2} maxLength={500} value={note} onChange={(e) => setNote(e.target.value)} disabled={busy} />
      </div>

      {error && (
        <p role="alert" className="rounded-md bg-destructive/10 px-3 py-2 text-sm text-destructive">
          {error}
        </p>
      )}

      <div className="flex flex-wrap items-center gap-2">
        <Button onClick={submitApprove} disabled={busy || !invoiceId}>
          {approve.isPending ? <Loader2 className="size-4 animate-spin" /> : <CheckCircle2 className="size-4" />}
          Approve allocation
        </Button>
        {canReject && (
          <Button variant="outline" className="text-destructive" onClick={() => setRejectOpen(true)} disabled={busy}>
            <ThumbsDown className="size-4" /> Reject candidate
          </Button>
        )}
      </div>

      <AlertDialog open={rejectOpen} onOpenChange={setRejectOpen}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>Reject the suggested match?</AlertDialogTitle>
            <AlertDialogDescription>
              The payment will be marked unmatched and no money is allocated. You can still allocate it to a different
              invoice afterwards. This decision is recorded in the audit log.
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel disabled={reject.isPending}>Keep reviewing</AlertDialogCancel>
            <Button variant="destructive" onClick={submitReject} disabled={reject.isPending}>
              {reject.isPending && <Loader2 className="size-4 animate-spin" />}
              Reject candidate
            </Button>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </section>
  )
}

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <div className="space-y-2">
      <h3 className="text-xs font-medium tracking-wide text-muted-foreground uppercase">{title}</h3>
      <div className="space-y-2 text-sm">{children}</div>
    </div>
  )
}

function Row({ label, children }: { label: string; children: ReactNode }) {
  return (
    <div className="flex justify-between gap-3">
      <span className="text-muted-foreground">{label}</span>
      <span className="text-right font-medium tabular-nums">{children}</span>
    </div>
  )
}
